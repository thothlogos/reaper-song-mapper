-- Load/run as a ReaScript. All mutations happen in a NEW disposable project tab.
-- Results: tests/integration-results.txt. Generated projects: tests/artifacts/.
local root = debug.getinfo(1, 'S').source:sub(2):match('^(.*[/\\])') .. '../'
package.path = root .. '?.lua;' .. package.path
local model = require('song_mapper.model')
local codec = require('song_mapper.codec')
local Project = require('song_mapper.project')
local Session = require('song_mapper.session')
local log = assert(io.open(root .. 'tests/integration-results.txt','w'))
local count = 0
local function out(s) log:write(s, '\n'); log:flush() end
local function test(name, fn) fn(); count=count+1; out('PASS '..name) end
local function near(a,b) assert(math.abs(a-b)<1e-6, tostring(a)..' ~= '..tostring(b)) end
local r = reaper
local original_project = r.EnumProjects(-1)
local artifacts = root .. 'tests/artifacts/' .. os.time() .. '/'
r.RecursiveCreateDirectory(artifacts,0)
r.Main_OnCommand(40859,0)
local p = r.EnumProjects(-1)
local adapter = Project.new(r,p)
local doc = model.example()
local success, failure = xpcall(function()
  out('REAPER '..r.GetAppVersion())
  local unrelated_id = r.AddProjectMarker2(p,true,80,90,'Keep this region',90,0)
  local marker_id = r.AddProjectMarker2(p,false,15,0,'Keep this marker',91,0)
  local initial_markers = adapter:markers()
  test('apply example with count-in and one marker at every section',function()
    local saved,err=adapter:apply(doc,''); assert(saved,err)
    assert(#saved.generated.regions==6 and #saved.generated.tempos==6)
    local expected=model.plan(doc)
    for i,m in ipairs(saved.generated.regions) do
      assert(m.name==expected.entries[i].name)
      near(m.position,expected.entries[i].start_seconds); near(m.finish,expected.entries[i].end_seconds)
    end
    assert(saved.generated.regions[2].color==saved.generated.regions[4].color)
    assert(saved.generated.regions[2].color~=saved.generated.regions[3].color)
    assert(not adapter:guard())
  end)
  local first_revision = adapter:revision()
  local first_payload = codec.encode(adapter:load())
  test('reapply replaces regions and keeps unrelated markers in absolute time',function()
    doc.sections[1].bpm=111.125
    assert(adapter:apply(doc,first_revision))
    assert(#adapter:markers()==8 and r.CountTempoTimeSigMarkers(p)==6)
    for _, before in ipairs(initial_markers) do
      local found
      for _,after in ipairs(adapter:markers()) do
        if before.id==after.id and before.region==after.region then
          found=true; assert(codec.encode(before)==codec.encode(after))
        end
      end
      assert(found)
    end
  end)
  local second_revision=adapter:revision()
  test('Undo restores timeline AND matching section list',function()
    r.Undo_DoUndo2(p)
    assert(adapter:revision()==first_revision)
    assert(codec.encode(adapter:load())==first_payload)
    assert(not adapter:guard())
  end)
  test('Redo restores the second revision',function()
    r.Undo_DoRedo2(p); assert(adapter:revision()==second_revision)
    assert(adapter:load().document.sections[1].bpm==111.125 and not adapter:guard())
  end)
  test('clean open editor follows Undo/Redo',function()
    local s=Session.new(adapter); r.Undo_DoUndo2(p); s:poll()
    assert(s.document.sections[1].bpm==110)
    r.Undo_DoRedo2(p); s:poll(); assert(s.document.sections[1].bpm==111.125)
  end)
  test('stale editor cannot overwrite a newer revision',function()
    local result,err=adapter:apply(doc,first_revision)
    assert(not result and err:find('changed'))
  end)
  test('renamed generated region blocks Apply',function()
    local m=adapter:load().generated.regions[2]
    r.Undo_BeginBlock2(p)
    r.SetProjectMarker3(p,m.id,true,m.position,m.finish,'Manual rename',m.color)
    r.Undo_EndBlock2(p,'Integration: rename',-1)
    assert(adapter:guard():find('region'))
    assert(not adapter:apply(doc,adapter:revision()))
    r.Undo_DoUndo2(p); assert(not adapter:guard())
  end)
  test('manual tempo edit blocks Apply',function()
    local t=adapter:tempos()[2]
    r.Undo_BeginBlock2(p)
    r.SetTempoTimeSigMarker(p,1,t.time,-1,-1,133,t.numerator,t.denominator,false)
    r.Undo_EndBlock2(p,'Integration: tempo edit',-1)
    assert(adapter:guard():find('tempo map'))
    r.Undo_DoUndo2(p); assert(not adapter:guard())
  end)
  test('media items make the map read-only',function()
    r.Undo_BeginBlock2(p)
    r.InsertTrackAtIndex(0,true)
    r.AddMediaItemToTrack(r.GetTrack(p,0))
    r.Undo_EndBlock2(p,'Integration: media item',-1)
    assert(adapter:guard():find('media items'))
    assert(not adapter:apply(doc,adapter:revision()))
    r.Undo_DoUndo2(p); assert(not adapter:guard())
  end)
  test('playback and recording guards',function()
    for _,state in ipairs({1,2,5}) do
      local api=setmetatable({GetPlayStateEx=function() return state end},{__index=r})
      assert(Project.new(api,p):guard():find('Stop playback'))
    end
  end)
  test('injected region-creation failure restores previous complete map',function()
    local before=codec.encode(adapter:load())
    local markers=codec.encode(adapter:markers())
    local revision=adapter:revision()
    local calls=0
    local api=setmetatable({AddProjectMarker2=function(...)
      calls=calls+1; if calls==3 then return -1 end; return r.AddProjectMarker2(...)
    end},{__index=r})
    local result,err=Project.new(api,p):apply(doc,revision)
    assert(not result and err:find('previous map was restored'),err)
    assert(adapter:revision()==revision and codec.encode(adapter:load())==before)
    assert(codec.encode(adapter:markers())==markers and not adapter:guard())
    local redo = r.Undo_CanRedo2(p)
    assert(redo == nil or redo == '', 'A failed partial apply must not remain available to Redo: ' .. tostring(redo))
  end)
  test('mixed meter and no count-in yield exact musical boundaries',function()
    doc=model.new(); doc.count_in=0
    for _,meter in ipairs({{4,4},{6,8},{7,8}}) do
      model.add(doc,{type='Verse',measures=1,bpm=120,numerator=meter[1],denominator=meter[2]})
    end
    assert(adapter:apply(doc,adapter:revision()))
    near(r.TimeMap_GetMeasureInfo(p,1),2)
    near(r.TimeMap_GetMeasureInfo(p,2),3.5)
    near(r.TimeMap_GetMeasureInfo(p,3),5.25)
    assert(#adapter:load().generated.regions==3)
  end)
  test('save and reopen preserves the applied map and conflict fingerprint',function()
    local before=codec.encode(adapter:load())
    r.Main_SaveProjectEx(p,artifacts .. 'mixed-meter.rpp',8)
    r.Main_openProject('noprompt:' .. artifacts .. 'mixed-meter.rpp')
    p=r.EnumProjects(-1); adapter=Project.new(r,p)
    assert(codec.encode(adapter:load())==before and not adapter:guard())
  end)
  test('project tab binding and pre-existing tempo map refusal',function()
    local bound=p
    r.Main_OnCommand(40859,0)
    local other=r.EnumProjects(-1)
    assert(adapter:guard():find('Switch back'))
    r.SetTempoTimeSigMarker(other,-1,-1,4,0,140,4,4,false)
    local other_adapter=Project.new(r,other)
    assert(other_adapter:guard():find('already has a tempo map'))
    r.SelectProjectInstance(bound)
    assert(not adapter:guard())
  end)
  -- Produce a clean sample without integration-test history or unrelated markers.
  r.Main_OnCommand(40859,0)
  local sample=r.EnumProjects(-1)
  assert(Project.new(r,sample):apply(model.example(),''))
  r.GetSet_ArrangeView2(sample,true,0,0,0,42)
  r.Main_SaveProjectEx(sample,root .. 'examples/Sample Song.rpp',8)
  r.AddRemoveReaScript(true,0,root .. 'Song Mapper.lua',true)
end, debug.traceback)
out(success and ('\n'..count..' integration tests passed') or ('FAIL\n'..tostring(failure)))
log:close()
if r.ValidatePtr(original_project,'ReaProject*') then r.SelectProjectInstance(original_project) end
r.ShowMessageBox(success and (count..' integration tests passed.\nA clean sample song was saved in examples/. Your original project is active again.')
  or ('Integration test failed. See tests/integration-results.txt.\n\n'..tostring(failure)), 'Song Mapper tests',0)
r.defer(function() end)
