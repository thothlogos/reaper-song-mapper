-- Developer probe. Creates a new disposable project tab; never edits the existing tab.
local root = debug.getinfo(1, 'S').source:sub(2):match('^(.*[/\\])') .. '../'
local log = assert(io.open(root .. 'tests/probe-results.txt', 'w'))
local function out(...) local args = {...}; for i,v in ipairs(args) do args[i]=tostring(v) end; log:write(table.concat(args,' | '), '\n'); log:flush() end
reaper.Main_OnCommand(40859, 0) -- New project tab
local p = reaper.EnumProjects(-1)
out('Version', reaper.GetAppVersion(), 'ImGui', reaper.APIExists('ImGui_GetBuiltinPath'))
out('initial ext', reaper.GetProjExtState(p, 'SongMapperProbe', 'test'))
reaper.Undo_BeginBlock2(p)
reaper.SetProjExtState(p, 'SongMapperProbe', 'test', 'one')
reaper.SetTempoTimeSigMarker(p, -1, -1, 0, 0, 110, 4, 4, false)
reaper.Undo_EndBlock2(p, 'Song Mapper probe', -1)
out('applied ext', reaper.GetProjExtState(p, 'SongMapperProbe', 'test'))
out('tempo count', reaper.CountTempoTimeSigMarkers(p))
reaper.Undo_DoUndo2(p)
out('undo ext', reaper.GetProjExtState(p, 'SongMapperProbe', 'test'))
out('tempo count', reaper.CountTempoTimeSigMarkers(p))
reaper.Undo_DoRedo2(p)
out('redo ext', reaper.GetProjExtState(p, 'SongMapperProbe', 'test'))
out('tempo count', reaper.CountTempoTimeSigMarkers(p))
out('tempo envelope', reaper.GetTrackEnvelopeByName(reaper.GetMasterTrack(p), 'Tempo map'))
reaper.Undo_DoUndo2(p)
local master = reaper.GetMasterTrack(p)
out('initial ref', reaper.GetSetMediaTrackInfo_String(master, 'P_EXT:SongMapperRevision', '', false))
reaper.Undo_BeginBlock2(p)
reaper.GetSetMediaTrackInfo_String(master, 'P_EXT:SongMapperRevision', 'revision1', true)
reaper.SetTempoTimeSigMarker(p, -1, -1, 0, 0, 120, 4, 4, false)
reaper.SetTempoTimeSigMarker(p, -1, -1, 4, 0, 120, 6, 8, false)
reaper.SetTempoTimeSigMarker(p, -1, -1, 6, 0, 120, 7, 8, false)
reaper.Undo_EndBlock2(p, 'Song Mapper revision probe', -1)
out('ref after', reaper.GetSetMediaTrackInfo_String(master, 'P_EXT:SongMapperRevision', '', false))
for i = 0, 8 do out('measure', i, reaper.TimeMap_GetMeasureInfo(p, i)) end
reaper.Undo_DoUndo2(p)
out('ref undo', reaper.GetSetMediaTrackInfo_String(reaper.GetMasterTrack(p), 'P_EXT:SongMapperRevision', '', false))
reaper.Undo_DoRedo2(p)
out('ref redo', reaper.GetSetMediaTrackInfo_String(reaper.GetMasterTrack(p), 'P_EXT:SongMapperRevision', '', false))
reaper.Undo_DoUndo2(p)
log:close()
reaper.defer(function() end)
